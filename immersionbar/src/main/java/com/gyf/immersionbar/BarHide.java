package com.gyf.immersionbar;

/**
 * System bar hide modes.
 *
 * @author geyifeng
 * @date 2017/4/25
 */
public enum BarHide {
    /**
     * Hide status bar.
     */
    FLAG_HIDE_STATUS_BAR,
    /**
     * Hide navigation bar.
     */
    FLAG_HIDE_NAVIGATION_BAR,
    /**
     * Hide both status bar and navigation bar.
     */
    FLAG_HIDE_BAR,
    /**
     * Show both status bar and navigation bar.
     */
    FLAG_SHOW_BAR
}
